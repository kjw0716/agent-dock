'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('hud', {
  onRows: (cb) => ipcRenderer.on('rows', (_e, rows) => cb(rows)),
  size: (h) => ipcRenderer.send('size', h),
  ready: () => ipcRenderer.send('ready'),
  expand: (on) => ipcRenderer.send('expand', !!on),
  answer: (req) => ipcRenderer.invoke('answer', req),
  setPlugin: (on) => ipcRenderer.invoke('plugin:set', !!on),
  dismiss: (agent, id, askId) => ipcRenderer.send('dismiss', { agent, id, askId }),
  openChat: (agent, id) => ipcRenderer.invoke('open', { agent, id }),
  markRead: (id) => ipcRenderer.send('read', id),
  resize: (dir, on) => ipcRenderer.send('resize', dir, !!on),
  view: (v) => ipcRenderer.send('view', String(v)),
  statsGet: (range) => ipcRenderer.invoke('stats:get', String(range)),
  statsNames: () => ipcRenderer.invoke('stats:names'),
  onStatsChanged: (cb) => ipcRenderer.on('stats:changed', () => cb()),
  onCloseStats: (cb) => ipcRenderer.on('close-stats', () => cb()),
  onOpenStats: (cb) => ipcRenderer.on('open-stats', () => cb()),
  phoneGet: () => ipcRenderer.invoke('phone:get'),
  phoneSet: (patch) => ipcRenderer.invoke('phone:set', patch),
  phonePair: () => ipcRenderer.invoke('phone:pair'),
  phoneRevoke: (id) => ipcRenderer.invoke('phone:revoke', id),
  phoneSetup: () => ipcRenderer.invoke('phone:setup'),
  phoneTest: () => ipcRenderer.invoke('phone:test'),
  phoneAddDir: () => ipcRenderer.invoke('phone:addDir'),
  phoneRemoveDir: (d) => ipcRenderer.invoke('phone:removeDir', d),
  phoneDownload: () => ipcRenderer.invoke('phone:download'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
});
